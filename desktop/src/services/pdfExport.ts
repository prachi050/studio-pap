import { jsPDF } from "jspdf";

export interface PdfAnalysis {
  captured_at: string;
  screenshot_data_url: string;

  design_score: number;

  accessibility_score: number;
  hierarchy_score: number;
  typography_score: number;
  spacing_score: number;
  color_score: number;

  screen_type: string;

  summary: string;
  top_priority: string;

  quick_wins: string[];
  suggestions: string[];
}

type RGB = [number, number, number];

const COLORS = {
  black: [24, 24, 27] as RGB,
  dark: [39, 39, 42] as RGB,
  gray: [113, 113, 122] as RGB,
  lightGray: [228, 228, 231] as RGB,
  softGray: [247, 247, 248] as RGB,
  white: [255, 255, 255] as RGB,

  accent: [181, 121, 32] as RGB,
  accentDark: [125, 78, 14] as RGB,
  accentSoft: [250, 244, 232] as RGB,

  green: [22, 101, 52] as RGB,
  greenSoft: [240, 253, 244] as RGB,

  red: [153, 27, 27] as RGB,
  redSoft: [254, 242, 242] as RGB,
};

const PAGE_WIDTH = 210;
const PAGE_HEIGHT = 297;

const MARGIN_X = 16;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN_X * 2;

const TOP_MARGIN = 18;
const BOTTOM_MARGIN = 20;

function setFill(pdf: jsPDF, color: RGB): void {
  pdf.setFillColor(color[0], color[1], color[2]);
}

function setDraw(pdf: jsPDF, color: RGB): void {
  pdf.setDrawColor(color[0], color[1], color[2]);
}

function setText(pdf: jsPDF, color: RGB): void {
  pdf.setTextColor(color[0], color[1], color[2]);
}

function roundedBox(
  pdf: jsPDF,
  x: number,
  y: number,
  width: number,
  height: number,
  fill: RGB,
  border?: RGB,
  radius = 3,
): void {
  setFill(pdf, fill);

  if (border) {
    setDraw(pdf, border);

    pdf.roundedRect(
      x,
      y,
      width,
      height,
      radius,
      radius,
      "FD",
    );

    return;
  }

  pdf.roundedRect(
    x,
    y,
    width,
    height,
    radius,
    radius,
    "F",
  );
}

function loadImage(source: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const image = new Image();

    image.onload = () => resolve(image);

    image.onerror = () => {
      reject(
        new Error(
          "Studio PAP could not load the analyzed screenshot.",
        ),
      );
    };

    image.src = source;
  });
}

function addPageHeader(pdf: jsPDF, label: string): void {
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(9);
  setText(pdf, COLORS.accentDark);

  pdf.text("STUDIO PAP", MARGIN_X, 12);

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(8);
  setText(pdf, COLORS.gray);

  pdf.text(label, PAGE_WIDTH - MARGIN_X, 12, {
    align: "right",
  });

  setDraw(pdf, COLORS.lightGray);
  pdf.setLineWidth(0.3);

  pdf.line(
    MARGIN_X,
    15,
    PAGE_WIDTH - MARGIN_X,
    15,
  );
}

function addSectionTitle(
  pdf: jsPDF,
  title: string,
  y: number,
  subtitle?: string,
): number {
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(16);
  setText(pdf, COLORS.black);

  pdf.text(title, MARGIN_X, y);

  let nextY = y + 7;

  if (subtitle) {
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(9.5);
    setText(pdf, COLORS.gray);

    const subtitleLines = pdf.splitTextToSize(
      subtitle,
      CONTENT_WIDTH,
    );

    pdf.text(subtitleLines, MARGIN_X, nextY);

    nextY += subtitleLines.length * 4.8;
  }

  return nextY + 3;
}

function addFooter(
  pdf: jsPDF,
  generatedDate: string,
): void {
  const totalPages = pdf.getNumberOfPages();

  for (
    let pageNumber = 1;
    pageNumber <= totalPages;
    pageNumber += 1
  ) {
    pdf.setPage(pageNumber);

    setDraw(pdf, COLORS.lightGray);
    pdf.setLineWidth(0.25);

    pdf.line(
      MARGIN_X,
      PAGE_HEIGHT - 14,
      PAGE_WIDTH - MARGIN_X,
      PAGE_HEIGHT - 14,
    );

    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(7.5);
    setText(pdf, COLORS.gray);

    pdf.text(
      `Generated by Studio PAP · ${generatedDate}`,
      MARGIN_X,
      PAGE_HEIGHT - 9,
    );

    pdf.text(
      `Page ${pageNumber} of ${totalPages}`,
      PAGE_WIDTH - MARGIN_X,
      PAGE_HEIGHT - 9,
      {
        align: "right",
      },
    );
  }
}

function scoreStatus(
  score: number,
): {
  label: string;
  fill: RGB;
  text: RGB;
} {
  if (score >= 85) {
    return {
      label: "Strong",
      fill: COLORS.greenSoft,
      text: COLORS.green,
    };
  }

  if (score >= 70) {
    return {
      label: "Good",
      fill: COLORS.accentSoft,
      text: COLORS.accentDark,
    };
  }

  return {
    label: "Needs attention",
    fill: COLORS.redSoft,
    text: COLORS.red,
  };
}

function addScoreCard(
  pdf: jsPDF,
  label: string,
  value: number,
  x: number,
  y: number,
  width: number,
): void {
  roundedBox(
    pdf,
    x,
    y,
    width,
    28,
    COLORS.softGray,
    COLORS.lightGray,
  );

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(8.5);
  setText(pdf, COLORS.gray);

  pdf.text(label, x + 4, y + 7);

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(18);
  setText(pdf, COLORS.black);

  pdf.text(String(value), x + 4, y + 18);

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(8);
  setText(pdf, COLORS.gray);

  pdf.text("/100", x + 15, y + 18);

  const status = scoreStatus(value);

  roundedBox(
    pdf,
    x + width - 29,
    y + 6,
    25,
    8,
    status.fill,
  );

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(6.8);
  setText(pdf, status.text);

  pdf.text(
    status.label,
    x + width - 16.5,
    y + 11.2,
    {
      align: "center",
    },
  );

  setFill(pdf, COLORS.lightGray);

  pdf.roundedRect(
    x + 4,
    y + 22,
    width - 8,
    2.6,
    1.3,
    1.3,
    "F",
  );

  setFill(
    pdf,
    value >= 70
      ? COLORS.accent
      : COLORS.red,
  );

  pdf.roundedRect(
    x + 4,
    y + 22,
    Math.max(
      2,
      ((width - 8) *
        Math.min(
          Math.max(value, 0),
          100,
        )) /
        100,
    ),
    2.6,
    1.3,
    1.3,
    "F",
  );
}

function addParagraphCard(
  pdf: jsPDF,
  title: string,
  text: string,
  y: number,
  options?: {
    background?: RGB;
    border?: RGB;
    titleColor?: RGB;
  },
): number {
  const cardPaddingX = 7;
  const cardPaddingTop = 8;
  const cardPaddingBottom = 9;

  const titleHeight = 8;
  const fontSize = 9.5;
  const lineHeightFactor = 1.3;

  const bodyMaxWidth =
    CONTENT_WIDTH - cardPaddingX * 2;

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(fontSize);

  const bodyLines = pdf.splitTextToSize(
    text || "No information available.",
    bodyMaxWidth,
  ) as string[];

  // Convert the rendered font height to millimetres.
  const renderedLineHeight =
    (fontSize * 0.3528) * lineHeightFactor;

  const bodyHeight =
    bodyLines.length * renderedLineHeight;

  const cardHeight =
    cardPaddingTop +
    titleHeight +
    bodyHeight +
    cardPaddingBottom;

  roundedBox(
    pdf,
    MARGIN_X,
    y,
    CONTENT_WIDTH,
    cardHeight,
    options?.background ?? COLORS.softGray,
    options?.border ?? COLORS.lightGray,
  );

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(10);

  setText(
    pdf,
    options?.titleColor ?? COLORS.accentDark,
  );

  pdf.text(
    title.toUpperCase(),
    MARGIN_X + cardPaddingX,
    y + cardPaddingTop,
  );

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(fontSize);
  setText(pdf, COLORS.dark);

  pdf.text(
    bodyLines,
    MARGIN_X + cardPaddingX,
    y + cardPaddingTop + titleHeight,
    {
      lineHeightFactor,
      maxWidth: bodyMaxWidth,
    },
  );

  return y + cardHeight + 6;
}
function addBulletList(
  pdf: jsPDF,
  items: string[],
  startY: number,
  sectionTitle: string,
  pageLabel: string,
): number {
  let y = startY;

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(16);
  setText(pdf, COLORS.black);

  pdf.text(sectionTitle, MARGIN_X, y);

  // More breathing room below the heading.
  y += 14;

  const listItems =
    items.length > 0
      ? items
      : ["No items available."];

  listItems.forEach((item, index) => {
    const textMaxWidth =
      CONTENT_WIDTH - 26;

    const lines = pdf.splitTextToSize(
      item,
      textMaxWidth,
    );

    const lineHeight = 4.8;

    // Tighter card height, but still grows for wrapped text.
    const itemHeight = Math.max(
      14,
      lines.length * lineHeight + 7,
    );

    if (
      y + itemHeight >
      PAGE_HEIGHT - BOTTOM_MARGIN
    ) {
      pdf.addPage();

      addPageHeader(pdf, pageLabel);

      y = TOP_MARGIN + 8;
    }

    roundedBox(
      pdf,
      MARGIN_X,
      y,
      CONTENT_WIDTH,
      itemHeight,
      COLORS.softGray,
      COLORS.lightGray,
    );

    const numberBoxSize = 8;
    const numberBoxY =
      y +
      (itemHeight - numberBoxSize) / 2;

    roundedBox(
      pdf,
      MARGIN_X + 5,
      numberBoxY,
      numberBoxSize,
      numberBoxSize,
      COLORS.accentSoft,
      undefined,
      2,
    );

    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(7.5);
    setText(pdf, COLORS.accentDark);

    pdf.text(
      String(index + 1),
      MARGIN_X + 9,
      numberBoxY + 5.2,
      {
        align: "center",
      },
    );

    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(9.5);
    setText(pdf, COLORS.dark);

    const textBlockHeight =
      lines.length * lineHeight;

    const textY =
      y +
      (itemHeight - textBlockHeight) / 2 +
      3.8;

    pdf.text(
      lines,
      MARGIN_X + 18,
      textY,
      {
        lineHeightFactor: 1.25,
        maxWidth: textMaxWidth,
      },
    );

    y += itemHeight + 5;
  });

  return y;
}

export async function exportAnalysisPdf(
  analysis: PdfAnalysis,
): Promise<void> {
  const pdf = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
    compress: true,
  });

  const generatedDate =
    new Date().toLocaleString();

  const capturedDate =
    new Date(
      analysis.captured_at,
    ).toLocaleString();

  /*
   * PAGE 1 — COVER AND OVERVIEW
   */

  setFill(pdf, COLORS.black);

  pdf.rect(
    0,
    0,
    PAGE_WIDTH,
    67,
    "F",
  );

  roundedBox(
    pdf,
    MARGIN_X,
    15,
    31,
    9,
    COLORS.accent,
  );

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(8);
  setText(pdf, COLORS.black);

  pdf.text(
    "STUDIO PAP",
    MARGIN_X + 15.5,
    20.8,
    {
      align: "center",
    },
  );

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(27);
  setText(pdf, COLORS.white);

  pdf.text(
    "AI Design",
    MARGIN_X,
    39,
  );

  pdf.text(
    "Analysis Report",
    MARGIN_X,
    50,
  );

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(9);
  setText(
    pdf,
    [212, 212, 216],
  );

  pdf.text(
    "Structured design intelligence for stronger digital experiences.",
    MARGIN_X,
    59,
  );

  roundedBox(
    pdf,
    148,
    18,
    46,
    36,
    COLORS.white,
  );

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(7.5);
  setText(pdf, COLORS.gray);

  pdf.text(
    "OVERALL SCORE",
    171,
    28,
    {
      align: "center",
    },
  );

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(26);
  setText(pdf, COLORS.black);

  pdf.text(
    String(
      analysis.design_score,
    ),
    171,
    42,
    {
      align: "center",
    },
  );

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(8);
  setText(pdf, COLORS.gray);

  pdf.text(
    "out of 100",
    171,
    49,
    {
      align: "center",
    },
  );

  let y = 77;

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(9);
  setText(pdf, COLORS.accentDark);

  pdf.text(
    "REPORT OVERVIEW",
    MARGIN_X,
    y,
  );

  y += 7;

  roundedBox(
    pdf,
    MARGIN_X,
    y,
    CONTENT_WIDTH,
    26,
    COLORS.softGray,
    COLORS.lightGray,
  );

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(8);
  setText(pdf, COLORS.gray);

  pdf.text(
    "CAPTURED",
    MARGIN_X + 6,
    y + 7,
  );

  pdf.text(
    "SCREEN TYPE",
    77,
    y + 7,
  );

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(9);
  setText(pdf, COLORS.dark);

  pdf.text(
    capturedDate,
    MARGIN_X + 6,
    y + 16,
  );

  const screenTypeLines =
    pdf.splitTextToSize(
      analysis.screen_type,
      105,
    );

  pdf.text(
    screenTypeLines,
    77,
    y + 16,
  );

  y += 36;

  /*
   * SCREENSHOT
   */

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(16);
  setText(pdf, COLORS.black);

  pdf.text(
    "Analyzed Screenshot",
    MARGIN_X,
    y,
  );

  y += 7;

  try {
    const image = await loadImage(
      analysis.screenshot_data_url,
    );

    const availableWidth =
      CONTENT_WIDTH - 6;

    const maxImageHeight = 112;

    const sourceWidth =
      image.naturalWidth ||
      image.width;

    const sourceHeight =
      image.naturalHeight ||
      image.height;

    const aspectRatio =
      sourceWidth / sourceHeight;

    let imageWidth =
      availableWidth;

    let imageHeight =
      imageWidth / aspectRatio;

    if (
      imageHeight >
      maxImageHeight
    ) {
      imageHeight =
        maxImageHeight;

      imageWidth =
        imageHeight *
        aspectRatio;
    }

    const frameHeight =
      imageHeight + 8;

    roundedBox(
      pdf,
      MARGIN_X,
      y,
      CONTENT_WIDTH,
      frameHeight,
      COLORS.softGray,
      COLORS.lightGray,
    );

    const imageX =
      MARGIN_X +
      (CONTENT_WIDTH -
        imageWidth) /
        2;

    pdf.addImage(
      analysis.screenshot_data_url,
      "PNG",
      imageX,
      y + 4,
      imageWidth,
      imageHeight,
      undefined,
      "FAST",
    );

    y += frameHeight + 7;
  } catch (error) {
    console.error(
      "PDF screenshot error:",
      error,
    );

    roundedBox(
      pdf,
      MARGIN_X,
      y,
      CONTENT_WIDTH,
      28,
      COLORS.redSoft,
      [254, 202, 202],
    );

    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(9);
    setText(pdf, COLORS.red);

    const screenshotErrorLines =
      pdf.splitTextToSize(
        "The analyzed screenshot could not be loaded, but the rest of the report was generated successfully.",
        CONTENT_WIDTH - 12,
      );

    pdf.text(
      screenshotErrorLines,
      MARGIN_X + 6,
      y + 11,
    );

    y += 36;
  }

  /*
   * PAGE 2 — SCORES AND SUMMARY
   */

  pdf.addPage();

  addPageHeader(
    pdf,
    "Design Score Breakdown",
  );

  y = addSectionTitle(
    pdf,
    "Design Score Breakdown",
    27,
    "A detailed view of the visual and usability categories evaluated by Studio PAP.",
  );

  const gap = 4;
  const cardWidth =
    (CONTENT_WIDTH - gap) / 2;

  addScoreCard(
    pdf,
    "Accessibility",
    analysis.accessibility_score,
    MARGIN_X,
    y,
    cardWidth,
  );

  addScoreCard(
    pdf,
    "Visual Hierarchy",
    analysis.hierarchy_score,
    MARGIN_X + cardWidth + gap,
    y,
    cardWidth,
  );

  y += 33;

  addScoreCard(
    pdf,
    "Typography",
    analysis.typography_score,
    MARGIN_X,
    y,
    cardWidth,
  );

  addScoreCard(
    pdf,
    "Spacing",
    analysis.spacing_score,
    MARGIN_X + cardWidth + gap,
    y,
    cardWidth,
  );

  y += 33;

  addScoreCard(
    pdf,
    "Color",
    analysis.color_score,
    MARGIN_X,
    y,
    cardWidth,
  );

  roundedBox(
    pdf,
    MARGIN_X + cardWidth + gap,
    y,
    cardWidth,
    28,
    COLORS.accentSoft,
    [232, 207, 161],
  );

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(8.5);
  setText(pdf, COLORS.gray);

  pdf.text(
    "Overall Design Score",
    MARGIN_X +
      cardWidth +
      gap +
      4,
    y + 7,
  );

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(18);
  setText(pdf, COLORS.accentDark);

  pdf.text(
    String(
      analysis.design_score,
    ),
    MARGIN_X +
      cardWidth +
      gap +
      4,
    y + 18,
  );

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(8);
  setText(pdf, COLORS.gray);

  pdf.text(
    "/100",
    MARGIN_X +
      cardWidth +
      gap +
      15,
    y + 18,
  );

  y += 40;

  y = addParagraphCard(
    pdf,
    "Executive Summary",
    analysis.summary,
    y,
  );

  if (
    y + 45 >
    PAGE_HEIGHT - BOTTOM_MARGIN
  ) {
    pdf.addPage();

    addPageHeader(
      pdf,
      "Priority Review",
    );

    y = TOP_MARGIN + 8;
  }

  y = addParagraphCard(
    pdf,
    "Top Priority",
    analysis.top_priority,
    y,
    {
      background:
        COLORS.accentSoft,
      border: [232, 207, 161],
      titleColor:
        COLORS.accentDark,
    },
  );

  /*
   * QUICK WINS
   */

  if (
    y + 45 >
    PAGE_HEIGHT - BOTTOM_MARGIN
  ) {
    pdf.addPage();

    addPageHeader(
      pdf,
      "Quick Wins",
    );

    y = TOP_MARGIN + 8;
  }

  y = addBulletList(
    pdf,
    analysis.quick_wins,
    y,
    "Quick Wins",
    "Quick Wins",
  );

  // Clear separation before recommendations.
  y += 14;

  /*
   * DESIGN RECOMMENDATIONS
   */

  if (
    y + 55 >
    PAGE_HEIGHT - BOTTOM_MARGIN
  ) {
    pdf.addPage();

    addPageHeader(
      pdf,
      "Design Recommendations",
    );

    y = TOP_MARGIN + 8;
  }

  addBulletList(
    pdf,
    analysis.suggestions,
    y,
    "Design Recommendations",
    "Design Recommendations",
  );

  addFooter(
    pdf,
    generatedDate,
  );

  const safeDate =
    new Date(
      analysis.captured_at,
    )
      .toISOString()
      .slice(0, 10);

  pdf.save(
    `Studio-PAP-Design-Report-${safeDate}.pdf`,
  );
}